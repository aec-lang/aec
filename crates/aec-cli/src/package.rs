pub fn has_lockfile(root: &Path) -> Result<bool> {
    Ok(existing_lock_path(root)?.is_some())
}

fn install_impl(
    root: &Path,
    registry: Option<&RegistryLocation>,
    trust_keys: &[PathBuf],
    refresh: bool,
) -> Result<Lockfile> {
    let manifest = load_manifest(root)?;
    validate_manifest(&manifest)?;
    let existing_path = existing_lock_path(root)?;
    if refresh && existing_path.is_some() {
        let source = read_lock_source(root)?.context("cannot read lockfile")?;
        parse_lockfile(&source)?;
    }
    validate_dependency_graph(root, &manifest, registry, trust_keys)?;
    let expected = build_lockfile(root, &manifest, registry, trust_keys)?;
    if existing_path.is_some() && !refresh {
        let current = load_lockfile(root)?.context("lockfile disappeared during install")?;
        validate_lockfile(root, &current)?;
        if !lockfiles_match(root, &current, &expected)? {
            bail!("lockfile is stale; refresh it with apm add/remove or remove it before install");
        }
        let canonical = serialize_lockfile(&expected)?;
        if read_lock_source(root)?.as_deref() != Some(canonical.as_str()) {
            save_lockfile(root, &expected)?;
        }
        return Ok(expected);
    }
    save_lockfile(root, &expected)?;
    Ok(expected)
}

fn build_lockfile(
    root: &Path,
    manifest: &Manifest,
    registry: Option<&RegistryLocation>,
    trust_keys: &[PathBuf],
) -> Result<Lockfile> {
    let mut entries = Vec::with_capacity(manifest.dependencies.len());
    for (name, raw_path) in &manifest.dependencies {
        let dependency = resolve_dependency(root, name, raw_path, registry, trust_keys)?;
        entries.push(LockEntry {
            name: dependency.name,
            version: dependency.version,
            path: lock_path_for(root, &dependency.path)?,
            tree: dependency.tree_digest,
        });
    }
    entries.sort_by(|left, right| left.name.cmp(&right.name));
    let lockfile = Lockfile { entries };
    validate_lock_shape(&lockfile)?;
    Ok(lockfile)
}

fn validate_dependency_graph(
    root: &Path,
    manifest: &Manifest,
    registry: Option<&RegistryLocation>,
    trust_keys: &[PathBuf],
) -> Result<()> {
    let canonical_root =
        fs::canonicalize(root).with_context(|| format!("cannot resolve {}", root.display()))?;
    let mut stack = BTreeSet::new();
    stack.insert(canonical_root);
    let mut visited = BTreeSet::new();
    validate_graph(
        manifest,
        root,
        registry,
        trust_keys,
        &mut stack,
        &mut visited,
    )
}

fn validate_graph(
    manifest: &Manifest,
    directory: &Path,
    registry: Option<&RegistryLocation>,
    trust_keys: &[PathBuf],
    stack: &mut BTreeSet<PathBuf>,
    visited: &mut BTreeSet<PathBuf>,
) -> Result<()> {
    let mut local_paths = BTreeSet::new();
    for (name, raw_path) in &manifest.dependencies {
        let dependency = resolve_dependency(directory, name, raw_path, registry, trust_keys)?;
        if !local_paths.insert(dependency.path.clone()) {
            bail!("dependency '{}' collides with another dependency path", name);
        }
        if stack.contains(&dependency.path) {
            bail!("dependency cycle detected at '{}'", dependency.path.display());
        }
        if visited.insert(dependency.path.clone()) {
            if let Some(child) = dependency.manifest {
                stack.insert(dependency.path.clone());
                validate_graph(
                    &child,
                    &dependency.path,
                    registry,
                    trust_keys,
                    stack,
                    visited,
                )?;
                stack.remove(&dependency.path);
            }
        }
    }
    Ok(())
}

pub fn list_dependencies(root: &Path) -> Result<Vec<DependencyInfo>> {
    let manifest = load_manifest(root)?;
    let mut dependencies = Vec::new();
    for (name, raw_path) in manifest.dependencies {
        let path = if parse_registry_coordinate(&raw_path)?.is_some() {
            locked_dependency_path(root, &name)?
        } else {
            PathBuf::from(resolve_dependency_path(root, Path::new(&raw_path))?)
        };
        let dependency_manifest = load_optional_manifest(&path)?;
        if let Some(dependency_manifest) = &dependency_manifest {
            if dependency_manifest.name != name {
                bail!(
                    "dependency '{}' contains package '{}' instead",
                    name,
                    dependency_manifest.name
                );
            }
        }
        dependencies.push(DependencyInfo {
            name,
            version: dependency_manifest
                .map(|manifest| manifest.version)
                .unwrap_or_else(|| "*".to_string()),
            path: path.to_string_lossy().into_owned(),
        });
    }
    Ok(dependencies)
}

pub fn dependency_tree(root: &Path) -> Result<String> {
    let manifest = load_manifest(root)?;
    let canonical_root =
        fs::canonicalize(root).with_context(|| format!("cannot resolve {}", root.display()))?;
    let mut lines = vec![format!("{}@{}", manifest.name, manifest.version)];
    let mut stack = BTreeSet::new();
    stack.insert(canonical_root);
    collect_tree(&manifest, root, root, "", &mut stack, &mut lines)?;
    Ok(lines.join("\n"))
}

pub fn load_lockfile(root: &Path) -> Result<Option<Lockfile>> {
    let Some(path) = existing_lock_path(root)? else {
        return Ok(None);
    };
    let source = read_limited_regular_file(&path, 4 * 1024 * 1024, "lockfile")
        .with_context(|| format!("cannot read {}", path.display()))?;
    let source = std::str::from_utf8(&source)
        .with_context(|| format!("lockfile {} is not UTF-8", path.display()))?;
    let lockfile = parse_lockfile(source)
        .with_context(|| format!("invalid {}", path.display()))?;
    validate_lockfile(root, &lockfile)?;
    Ok(Some(lockfile))
}

pub fn validate_lockfile(root: &Path, lockfile: &Lockfile) -> Result<()> {
    validate_lock_shape(lockfile)?;
    let canonical_root = fs::canonicalize(root)
        .with_context(|| format!("cannot resolve {}", root.display()))?;
    let mut paths = BTreeSet::new();
    for entry in &lockfile.entries {
        let path = resolve_lock_path(root, &entry.path)?;
        if path == canonical_root {
            bail!("lockfile dependency '{}' resolves to the package root", entry.name);
        }
        if !paths.insert(path.clone()) {
            bail!("lockfile dependency '{}' collides with another path", entry.name);
        }
        let manifest = load_optional_manifest(&path)?;
        match manifest {
            Some(manifest) if manifest.name == entry.name => {
                if manifest.version != entry.version {
                    bail!(
                        "lockfile dependency '{}' has version '{}' but the package is '{}'",
                        entry.name,
                        entry.version,
                        manifest.version
                    );
                }
            }
            Some(manifest) => bail!(
                "lockfile dependency '{}' contains package '{}' instead",
                entry.name,
                manifest.name
            ),
            None if entry.version != "*" => {
                bail!("lockfile dependency '{}' has no package manifest", entry.name)
            }
            None => {}
        }
    }
    Ok(())
}

pub fn save_lockfile(root: &Path, lockfile: &Lockfile) -> Result<()> {
    ensure_real_directory(root)?;
    if path_exists(&root.join(LOCK_FILE))? && path_exists(&root.join(LEGACY_LOCK_FILE))? {
        bail!("both apm.lock and aecpm.lock exist; remove the legacy lockfile");
    }
    validate_lock_shape(lockfile)?;
    let source = serialize_lockfile(lockfile)?;
    let target = if path_exists(&root.join(LEGACY_LOCK_FILE))?
        && !path_exists(&root.join(LOCK_FILE))?
    {
        root.join(LEGACY_LOCK_FILE)
    } else {
        root.join(LOCK_FILE)
    };
    reject_symlink(&target)?;
    write_atomic(&target, &source)
}

fn lockfiles_match(root: &Path, left: &Lockfile, right: &Lockfile) -> Result<bool> {
    if left.entries.len() != right.entries.len() {
        return Ok(false);
    }
    for (left_entry, right_entry) in left.entries.iter().zip(&right.entries) {
        if left_entry.name != right_entry.name || left_entry.version != right_entry.version {
            return Ok(false);
        }
        if resolve_lock_path(root, &left_entry.path)? != resolve_lock_path(root, &right_entry.path)? {
            return Ok(false);
        }
    }
    Ok(true)
}

fn existing_lock_path(root: &Path) -> Result<Option<PathBuf>> {
    let current = root.join(LOCK_FILE);
    let legacy = root.join(LEGACY_LOCK_FILE);
    let current_exists = path_exists(&current)?;
    let legacy_exists = path_exists(&legacy)?;
    if current_exists && legacy_exists {
        bail!("both apm.lock and aecpm.lock exist; remove the legacy lockfile");
    }
    Ok(if current_exists {
        Some(current)
    } else if legacy_exists {
        Some(legacy)
    } else {
        None
    })
}

fn read_lock_source(root: &Path) -> Result<Option<String>> {
    let Some(path) = existing_lock_path(root)? else {
        return Ok(None);
    };
    let source = read_limited_regular_file(&path, 4 * 1024 * 1024, "lockfile")
        .with_context(|| format!("cannot read {}", path.display()))?;
    let source = std::str::from_utf8(&source)
        .with_context(|| format!("lockfile {} is not UTF-8", path.display()))?
        .to_string();
    Ok(Some(source))
}

fn validate_lock_shape(lockfile: &Lockfile) -> Result<()> {
    let mut previous = None;
    let mut names = BTreeSet::new();
    for entry in &lockfile.entries {
        validate_package_name(&entry.name)?;
        if entry.version != "*" {
            validate_version(&entry.version)?;
        }
        if entry.path.trim().is_empty()
            || entry.path.contains('\0')
            || entry.path.len() > MAX_RELATIVE_PATH_BYTES * 4
        {
            bail!("lockfile dependency '{}' has an invalid path", entry.name);
        }
        if let Some(tree) = &entry.tree {
            validate_sha256_hex(tree, "lockfile tree digest")
                .with_context(|| format!("lockfile dependency '{}'", entry.name))?;
        }
        if previous.is_some_and(|name| name >= entry.name.as_str()) {
            bail!("lockfile entries must be sorted by unique name");
        }
        if !names.insert(entry.name.as_str()) {
            bail!("lockfile contains duplicate dependency '{}'", entry.name);
        }
        previous = Some(entry.name.as_str());
    }
    Ok(())
}

fn serialize_lockfile(lockfile: &Lockfile) -> Result<String> {
    validate_lock_shape(lockfile)?;
    let mut source = String::from("# generated by apm install\n");
    for entry in &lockfile.entries {
        match &entry.tree {
            Some(tree) => source.push_str(&format!(
                "{} = {{ version = \"{}\", path = \"{}\", tree = \"{}\" }}\n",
                entry.name,
                escape(&entry.version),
                escape(&entry.path),
                tree
            )),
            None => source.push_str(&format!(
                "{} = {{ version = \"{}\", path = \"{}\" }}\n",
                entry.name,
                escape(&entry.version),
                escape(&entry.path)
            )),
        }
    }
    Ok(source)
}

fn parse_lockfile(source: &str) -> Result<Lockfile> {
    if !source.ends_with('\n') || source.contains('\r') {
        bail!("lockfile is not canonical LF-terminated data");
    }
    let body = source
        .strip_suffix('\n')
        .context("lockfile is missing its final newline")?;
    let mut lines = body.split('\n');
    if lines.next() != Some(LOCK_HEADER) {
        bail!("unsupported lockfile header");
    }
    let mut entries = Vec::new();
    for (index, line) in lines.enumerate() {
        if line.trim().is_empty() {
            bail!("lockfile contains a blank entry on line {}", index + 2);
        }
        let (name, raw_value) = line
            .split_once('=')
            .with_context(|| format!("lockfile line {} is not a key/value pair", index + 2))?;
        let name = name.trim();
        validate_package_name(name)
            .with_context(|| format!("lockfile line {}", index + 2))?;
        let raw_value = raw_value.trim();
        let inner = raw_value
            .strip_prefix('{')
            .and_then(|value| value.strip_suffix('}'))
            .context("lockfile entry must be an inline table")?;
        let fields = split_inline_fields(inner)?;
        if fields.len() < 2 || fields.len() > 3 {
            bail!(
                "lockfile entry '{}' must contain version, path and an optional tree digest",
                name
            );
        }
        let mut version = None;
        let mut path = None;
        let mut tree = None;
        for field in fields {
            let (key, raw_field_value) = field
                .split_once('=')
                .context("lockfile inline table contains an invalid field")?;
            match key.trim() {
                "version" if version.is_none() => {
                    version = Some(parse_quoted_lock_value(
                        raw_field_value.trim(),
                        "lockfile version",
                    )?);
                }
                "path" if path.is_none() => {
                    path = Some(parse_quoted_lock_value(raw_field_value.trim(), "lockfile path")?);
                }
                "tree" if tree.is_none() => {
                    tree = Some(parse_quoted_lock_value(raw_field_value.trim(), "lockfile tree")?);
                }
                _ => bail!("lockfile entry '{}' contains an unknown field", name),
            }
        }
        entries.push(LockEntry {
            name: name.to_string(),
            version: version.context("lockfile entry is missing version")?,
            path: path.context("lockfile entry is missing path")?,
            tree,
        });
    }
    let lockfile = Lockfile { entries };
    validate_lock_shape(&lockfile)?;
    Ok(lockfile)
}

fn split_inline_fields(value: &str) -> Result<Vec<&str>> {
    let mut fields = Vec::new();
    let mut start = 0;
    let mut quoted = false;
    let mut escaped = false;
    for (index, character) in value.char_indices() {
        if escaped {
            escaped = false;
        } else if character == '\\' && quoted {
            escaped = true;
        } else if character == '"' {
            quoted = !quoted;
        } else if character == ',' && !quoted {
            fields.push(value[start..index].trim());
            start = index + character.len_utf8();
        }
    }
    if quoted || escaped {
        bail!("lockfile inline table has an unterminated string");
    }
    fields.push(value[start..].trim());
    if fields.iter().any(|field| field.is_empty()) {
        bail!("lockfile inline table contains an empty field");
    }
    Ok(fields)
}

fn parse_quoted_lock_value(value: &str, label: &str) -> Result<String> {
    let mut characters = value.chars();
    if characters.next() != Some('"') {
        bail!("{label} must be quoted");
    }
    let mut result = String::new();
    let mut closed = false;
    while let Some(character) = characters.next() {
        match character {
            '"' => {
                closed = true;
                if characters.next().is_some() {
                    bail!("{label} contains data after its closing quote");
                }
                break;
            }
            '\\' => match characters.next() {
                Some('"') => result.push('"'),
                Some('\\') => result.push('\\'),
                _ => bail!("{label} contains an unsupported escape"),
            },
            character if character.is_control() => {
                bail!("{label} contains a control character")
            }
            character => result.push(character),
        }
    }
    if !closed {
        bail!("{label} must be quoted");
    }
    Ok(result)
}

fn collect_tree(
    manifest: &Manifest,
    directory: &Path,
    project_root: &Path,
    prefix: &str,
    stack: &mut BTreeSet<PathBuf>,
    lines: &mut Vec<String>,
) -> Result<()> {
    let count = manifest.dependencies.len();
    for (index, (name, raw_path)) in manifest.dependencies.iter().enumerate() {
        let path = if parse_registry_coordinate(raw_path)?.is_some() {
            locked_dependency_path(project_root, name)?
        } else {
            PathBuf::from(resolve_dependency_path(directory, Path::new(raw_path))?)
        };
        let child = load_optional_manifest(&path)?;
        if let Some(child) = &child {
            if child.name != *name {
                bail!(
                    "dependency '{}' contains package '{}' instead",
                    name,
                    child.name
                );
            }
        }
        let version = child
            .as_ref()
            .map(|manifest| manifest.version.clone())
            .unwrap_or_else(|| "*".to_string());
        let last = index + 1 == count;
        let branch = if last { "└── " } else { "├── " };
        lines.push(format!("{}{}{}@{}", prefix, branch, name, version));
        if stack.contains(&path) {
            lines.push(format!("{}└── (cycle)", prefix));
            continue;
        }
        if let Some(child) = child {
            stack.insert(path.clone());
            let child_prefix = format!("{}{}", prefix, if last { "    " } else { "│   " });
            collect_tree(
                &child,
                &path,
                project_root,
                &child_prefix,
                stack,
                lines,
            )?;
            stack.remove(&path);
        }
    }
    Ok(())
}

fn load_optional_manifest(root: &Path) -> Result<Option<Manifest>> {
    ensure_real_directory(root)?;
    let path = manifest_path(root)?;
    if !path_exists(&path)? {
        return Ok(None);
    }
    let source = read_limited_regular_file(&path, MAX_PACKAGE_FILE_SIZE, "manifest")
        .with_context(|| format!("cannot read {}", path.display()))?;
    let source = std::str::from_utf8(&source)
        .with_context(|| format!("manifest {} is not UTF-8", path.display()))?;
    parse_manifest(source)
        .with_context(|| format!("invalid {}", path.display()))
        .map(Some)
}

fn manifest_path(root: &Path) -> Result<PathBuf> {
    let current = root.join(MANIFEST_FILE);
    let legacy = root.join(LEGACY_MANIFEST_FILE);
    let current_exists = path_exists(&current)?;
    let legacy_exists = path_exists(&legacy)?;
    if current_exists && legacy_exists {
        bail!("both apm.toml and aecpm.toml exist; remove the legacy manifest");
    }
    Ok(if current_exists {
        current
    } else if legacy_exists {
        legacy
    } else {
        current
    })
}

fn parse_manifest(source: &str) -> Result<Manifest> {
    let mut section = String::new();
    let mut name = None;
    let mut version = None;
    let mut dependencies = BTreeMap::new();
    for (line_number, raw_line) in source.lines().enumerate() {
        let line = raw_line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        if line.starts_with('[') && line.ends_with(']') {
            section = line[1..line.len() - 1].to_string();
            if section != "package" && section != "dependencies" {
                bail!("unknown manifest section '{}'", section);
            }
            continue;
        }
        let Some((key, raw_value)) = line.split_once('=') else {
            bail!("line {} is not a key/value pair", line_number + 1);
        };
        let key = key.trim();
        let value = unescape(raw_value.trim());
        if value.is_empty() {
            bail!("line {} has an empty value", line_number + 1);
        }
        match section.as_str() {
            "package" if key == "name" => {
                if name.replace(value).is_some() {
                    bail!("duplicate package.name on line {}", line_number + 1);
                }
            }
            "package" if key == "version" => {
                if version.replace(value).is_some() {
                    bail!("duplicate package.version on line {}", line_number + 1);
                }
            }
            "dependencies" => {
                validate_package_name(key).with_context(|| format!("line {}", line_number + 1))?;
                if dependencies.insert(key.to_string(), value).is_some() {
                    bail!("duplicate dependency '{}' on line {}", key, line_number + 1);
                }
            }
            _ => bail!("unknown manifest entry on line {}", line_number + 1),
        }
    }
    let name = name.context("manifest is missing package.name")?;
    validate_package_name(&name)?;
    let version = version.context("manifest is missing package.version")?;
    validate_version(&version)?;
    let manifest = Manifest {
        name,
        version,
        dependencies,
    };
    validate_manifest(&manifest)?;
    Ok(manifest)
}

fn default_package_name(root: &Path) -> String {
    let candidate = root
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("aec-package");
    if validate_package_name(candidate).is_ok() {
        candidate.to_string()
    } else {
        "aec-package".to_string()
    }
}

fn parse_registry_coordinate(value: &str) -> Result<Option<RegistryCoordinate>> {
    let Some(rest) = value
        .strip_prefix("registry://")
        .or_else(|| value.strip_prefix("registry:"))
    else {
        return Ok(None);
    };
    if rest.is_empty() {
        bail!("registry dependency must contain a package coordinate");
    }
    let (name, version) = if let Some((name, version)) = rest.rsplit_once('@') {
        (name, version)
    } else if let Some((name, version)) = rest.rsplit_once('/') {
        (name, version)
    } else {
        bail!("registry dependency must use registry://<name>@<version>");
    };
    if name.is_empty() || version.is_empty() || name.contains('/') || version.contains('/') {
        bail!("registry dependency has an invalid package coordinate");
    }
    validate_package_name(name)?;
    validate_version(version)?;
    Ok(Some(RegistryCoordinate {
        name: name.to_string(),
        version: version.to_string(),
        source: format!("registry://{name}@{version}"),
    }))
}

fn validate_manifest(manifest: &Manifest) -> Result<()> {
    validate_package_name(&manifest.name)?;
    validate_version(&manifest.version)?;
    for (name, path) in &manifest.dependencies {
        validate_package_name(name)?;
        if path.trim().is_empty() || path.contains('\0') {
            bail!("dependency '{}' has an empty or invalid path", name);
        }
        parse_registry_coordinate(path)
            .with_context(|| format!("invalid dependency '{}'", name))?;
    }
    Ok(())
}

fn resolve_dependency_path(root: &Path, path: &Path) -> Result<String> {
    let joined = if path.is_absolute() {
        path.to_path_buf()
    } else {
        root.join(path)
    };
    ensure_no_symlink_components(&joined)?;
    let canonical = fs::canonicalize(&joined)
        .with_context(|| format!("cannot resolve dependency path {}", joined.display()))?;
    ensure_real_directory(&canonical)?;
    Ok(canonical.to_string_lossy().into_owned())
}

fn relative_to_root(root: &Path, path: &Path) -> Option<String> {
    let root = fs::canonicalize(root).ok()?;
    let relative = path.strip_prefix(root).ok()?;
    Some(normalize_lock_path(relative))
}

fn validate_package_name(name: &str) -> Result<()> {
    if name.is_empty()
        || !name.chars().all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '-'
        })
    {
        bail!(
            "invalid package name '{}'; use letters, numbers, '_' or '-'",
            name
        );
    }
    Ok(())
}

fn validate_version(version: &str) -> Result<()> {
    if version.is_empty()
        || !version.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '.' | '-' | '+')
        })
        || !version.chars().any(|character| character.is_ascii_digit())
    {
        bail!("invalid version '{}'; use a version such as 0.1.0", version);
    }
    Ok(())
}

fn write_atomic(path: &Path, contents: &str) -> Result<()> {
    let parent = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    ensure_real_directory(parent)?;
    reject_symlink(path)?;
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .context("output path must name a file")?;
    for sequence in 0..128_u64 {
        let temporary = parent.join(format!(
            ".{file_name}.{}.{sequence}.tmp",
            std::process::id()
        ));
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        options.mode(0o644);
        let mut file = match options.open(&temporary) {
            Ok(file) => file,
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(error) => {
                return Err(error)
                    .with_context(|| format!("cannot write {}", temporary.display()))
            }
        };
        let result = file
            .write_all(contents.as_bytes())
            .and_then(|_| file.sync_all())
            .and_then(|_| {
                drop(file);
                fs::rename(&temporary, path)
            });
        if let Err(error) = result {
            let _ = fs::remove_file(&temporary);
            return Err(error).with_context(|| format!("cannot replace {}", path.display()));
        }
        return Ok(());
    }
    bail!("cannot allocate a unique temporary output file")
}

fn reject_symlink(path: &Path) -> Result<()> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            bail!("path must not be a symbolic link: {}", path.display())
        }
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("cannot inspect {}", path.display())),
    }
}

fn ensure_no_symlink_components(path: &Path) -> Result<()> {
    let absolute = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()
            .with_context(|| "cannot resolve current directory")?
            .join(path)
    };
    let trusted = trusted_system_prefixes();
    let mut current = PathBuf::new();
    for component in absolute.components() {
        current.push(component.as_os_str());
        // System plumbing is not attacker-controlled and is symlinked on
        // purpose: `/var` is a link to `/private/var` on macOS and the
        // platform temp directory lives below it, and Windows temp roots
        // contain junctions. Rejecting those would make every package under
        // the platform temp directory unusable. Only components *below* a
        // system prefix are security-relevant, because that is where a link
        // could redirect a read or a write into someone else's tree.
        if trusted.iter().any(|prefix| prefix.starts_with(&current)) {
            continue;
        }
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                bail!("path must not contain a symbolic link: {}", current.display())
            }
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(error)
                    .with_context(|| format!("cannot inspect {}", current.display()))
            }
        }
    }
    Ok(())
}

/// Path prefixes whose own components are allowed to be symlinks.
///
/// Both the lexical and the canonical spelling of the platform temp directory
/// and the working directory are included, so a link such as macOS' `/var`
/// is recognized even though canonicalizing it turns the path into
/// `/private/var/...`.
fn trusted_system_prefixes() -> Vec<PathBuf> {
    let mut prefixes = Vec::new();
    for candidate in [std::env::temp_dir(), std::env::current_dir().unwrap_or_default()] {
        prefixes.push(candidate.clone());
        if let Ok(canonical) = fs::canonicalize(&candidate) {
            prefixes.push(canonical);
        }
    }
    prefixes
}

fn normalize_lock_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

fn resolve_dependency(
    root: &Path,
    name: &str,
    raw_path: &str,
    registry: Option<&RegistryLocation>,
    trust_keys: &[PathBuf],
) -> Result<ResolvedDependency> {
    if let Some(coordinate) = parse_registry_coordinate(raw_path)? {
        let registry = registry.context(
            "registry dependency requires --registry; local path syntax cannot identify a registry",
        )?;
        if trust_keys.is_empty() {
            bail!("registry dependency requires at least one --trust-key");
        }
        let (path, tree_digest) = match registry {
            RegistryLocation::Local(registry_path) => {
                let verified = verify_package_with_trust_keys(
                    registry_path,
                    &coordinate.name,
                    &coordinate.version,
                    trust_keys,
                )?;
                let path =
                    materialize_registry_package(root, &coordinate, registry_path, &verified)?;
                (path, verified.tree_digest)
            }
            RegistryLocation::Remote(base) => {
                remote::install(root, &coordinate, base, trust_keys)?
            }
        };
        let manifest = load_optional_manifest(&path)?;
        let manifest = manifest.context("materialized registry package is missing apm.toml")?;
        if manifest.name != coordinate.name || manifest.version != coordinate.version {
            bail!("materialized registry package identity does not match its coordinate");
        }
        return Ok(ResolvedDependency {
            name: name.to_string(),
            version: coordinate.version,
            path,
            manifest: Some(manifest),
            tree_digest: Some(tree_digest),
        });
    }
    let path = PathBuf::from(resolve_dependency_path(root, Path::new(raw_path))?);
    let manifest = load_optional_manifest(&path)?;
    if let Some(manifest) = &manifest {
        validate_manifest(manifest)?;
        if manifest.name != name {
            bail!(
                "dependency '{}' contains package '{}' instead",
                name,
                manifest.name
            );
        }
    }
    Ok(ResolvedDependency {
        name: name.to_string(),
        version: manifest
            .as_ref()
            .map(|manifest| manifest.version.clone())
            .unwrap_or_else(|| "*".to_string()),
        path,
        manifest,
        tree_digest: None,
    })
}

fn lock_path_for(root: &Path, path: &Path) -> Result<String> {
    let canonical_root = fs::canonicalize(root)
        .with_context(|| format!("cannot resolve {}", root.display()))?;
    let canonical_path = fs::canonicalize(path)
        .with_context(|| format!("cannot resolve {}", path.display()))?;
    Ok(match canonical_path.strip_prefix(&canonical_root) {
        Ok(relative) => normalize_lock_path(relative),
        Err(_) => normalize_lock_path(&canonical_path),
    })
}

fn resolve_lock_path(root: &Path, raw_path: &str) -> Result<PathBuf> {
    if raw_path.trim().is_empty() || raw_path.contains('\0') {
        bail!("lockfile dependency path is empty or invalid");
    }
    let path = Path::new(raw_path);
    let joined = if path.is_absolute() {
        path.to_path_buf()
    } else {
        root.join(path)
    };
    ensure_no_symlink_components(&joined)?;
    let canonical = fs::canonicalize(&joined)
        .with_context(|| format!("cannot resolve lockfile dependency {}", joined.display()))?;
    ensure_real_directory(&canonical)?;
    Ok(canonical)
}

fn locked_dependency_path(root: &Path, name: &str) -> Result<PathBuf> {
    let lockfile = load_lockfile(root)?.context(
        "registry dependencies must be installed before they can be listed or inspected",
    )?;
    let entry = lockfile
        .entries
        .iter()
        .find(|entry| entry.name == name)
        .with_context(|| format!("lockfile has no entry for dependency '{}'", name))?;
    resolve_lock_path(root, &entry.path)
}

fn materialize_registry_package(
    root: &Path,
    coordinate: &RegistryCoordinate,
    registry: &Path,
    verified: &RegistryPackage,
) -> Result<PathBuf> {
    if let Some(payload) = cached_package_payload(root, coordinate, &verified.tree_digest)? {
        return Ok(payload);
    }
    let cache_root = root.join(CACHE_DIRECTORY);
    create_real_directory(&cache_root)?;
    let packages = cache_root.join(REGISTRY_PACKAGES_DIRECTORY);
    create_real_directory(&packages)?;
    let package_parent = packages.join(&coordinate.name);
    create_real_directory(&package_parent)?;
    let staging_root = cache_root.join(REGISTRY_STAGING_DIRECTORY);
    create_real_directory(&staging_root)?;
    let staging_directory = create_staging_directory(&staging_root)?;
    let guard = StagingGuard {
        path: staging_directory.clone(),
    };
    let staged_payload = staging_directory.join(REGISTRY_PAYLOAD_DIRECTORY);
    fs::create_dir(&staged_payload).with_context(|| {
        format!(
            "cannot create registry cache staging directory {}",
            staged_payload.display()
        )
    })?;
    let source_payload = registry
        .join(REGISTRY_PACKAGES_DIRECTORY)
        .join(&coordinate.name)
        .join(&coordinate.version)
        .join(REGISTRY_PAYLOAD_DIRECTORY);
    let mut state = CopyState::default();
    copy_package_tree(&source_payload, &staged_payload, Path::new(""), 0, &mut state)?;
    let inspection = inspect_payload(&staged_payload)?;
    if inspection.tree_digest != verified.tree_digest {
        bail!("registry payload changed after verification");
    }
    let manifest = load_registry_manifest(&staged_payload)?;
    if manifest.name != coordinate.name || manifest.version != coordinate.version {
        bail!("registry payload identity changed after verification");
    }
    commit_staged_package(root, coordinate, &verified.tree_digest, staging_directory, guard)
}

/// Returns the cached payload directory when an installed copy of
/// `coordinate` exists and still hashes to `tree_digest`.
///
/// The payload directory is the one that contains `apm.toml`, so callers can
/// treat the returned path as the package root.
fn cached_package_payload(
    root: &Path,
    coordinate: &RegistryCoordinate,
    tree_digest: &str,
) -> Result<Option<PathBuf>> {
    let destination = root
        .join(CACHE_DIRECTORY)
        .join(REGISTRY_PACKAGES_DIRECTORY)
        .join(&coordinate.name)
        .join(&coordinate.version);
    if !path_exists(&destination)? {
        return Ok(None);
    }
    ensure_real_directory(&destination)?;
    let payload_destination = destination.join(REGISTRY_PAYLOAD_DIRECTORY);
    ensure_real_directory(&payload_destination)?;
    let existing = inspect_payload(&payload_destination)?;
    if existing.tree_digest != tree_digest {
        bail!(
            "cached registry package '{}' has a different tree digest",
            coordinate.name
        );
    }
    Ok(Some(payload_destination))
}

/// Atomically moves a verified staged package into the on-disk cache and
/// returns the payload directory that becomes the lockfile package root.
fn commit_staged_package(
    root: &Path,
    coordinate: &RegistryCoordinate,
    tree_digest: &str,
    staging_directory: PathBuf,
    guard: StagingGuard,
) -> Result<PathBuf> {
    let packages = root.join(CACHE_DIRECTORY).join(REGISTRY_PACKAGES_DIRECTORY);
    create_real_directory(&packages)?;
    let package_parent = packages.join(&coordinate.name);
    create_real_directory(&package_parent)?;
    let destination = package_parent.join(&coordinate.version);
    let payload_destination = destination.join(REGISTRY_PAYLOAD_DIRECTORY);
    if let Err(error) = rename_no_replace(&staging_directory, &destination) {
        if path_exists(&destination)? {
            drop(guard);
            return match cached_package_payload(root, coordinate, tree_digest)? {
                Some(payload) => Ok(payload),
                None => bail!(
                    "cached registry package '{}' appeared and vanished while installing",
                    coordinate.name
                ),
            };
        }
        return Err(error).with_context(|| {
            format!(
                "cannot atomically materialize registry package {}",
                destination.display()
            )
        });
    }
    drop(guard);
    Ok(payload_destination)
}

fn escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

fn unescape(value: &str) -> String {
    value
        .strip_prefix('"')
        .and_then(|value| value.strip_suffix('"'))
        .unwrap_or(value)
        .replace("\\\"", "\"")
        .replace("\\\\", "\\")
}

